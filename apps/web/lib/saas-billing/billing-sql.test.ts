import assert from "node:assert/strict";
import test from "node:test";
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
type Database = { exec: (sql: string) => Promise<unknown>; query: <T>(sql: string, args?: unknown[]) => Promise<{ rows: T[] }>; close: () => Promise<unknown> };
const a = "11111111-1111-4111-8111-111111111111", b = "22222222-2222-4222-8222-222222222222", outsider = "99999999-9999-4999-8999-999999999999";
const sid = "33333333-3333-4333-8333-333333333333", otherSid = "44444444-4444-4444-8444-444444444444";
test("commercial SQL isolates users, revocation, immutable bindings, retries and leases without changing engines", { skip: !process.env.PGLITE_MODULE_PATH }, async () => {
  const databaseModule = createRequire(import.meta.url)(process.env.PGLITE_MODULE_PATH!) as { PGlite: new () => Database };
  const db = new databaseModule.PGlite();
  const act = async (role: string, user = a) => db.exec(`reset role; select set_config('request.jwt.claims','${JSON.stringify({ role, sub: user })}',false); set role ${role};`);
  const p = (id = a, subscription = sid, version = 1, extra = {}) => ({ product_key: "coinops", external_tenant_id: id,
    billing_subscription_id: subscription, version, status: "active", tenant_name: "Fixture", checkout_url: "private-token", contact: "private-contact", ...extra });
  const apply = (value: unknown, nonce = randomUUID(), event = randomUUID()) => db.query<{ applied: boolean }>("select coinops.apply_saas_billing_projection($1::jsonb,$2::uuid,$3::uuid,'subscription.updated') as applied", [JSON.stringify(value), event, nonce]);
  try {
    await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
      create schema auth;create schema coinops;create schema private;
      create function auth.role()returns text language sql stable as $$select current_setting('request.jwt.claims',true)::jsonb->>'role'$$;
      create function auth.uid()returns uuid language sql stable as $$select(current_setting('request.jwt.claims',true)::jsonb->>'sub')::uuid$$;
      grant usage on schema auth,coinops,private to anon,authenticated,service_role;
      create table auth.users(id uuid primary key,deleted_at timestamptz,banned_until timestamptz,raw_user_meta_data jsonb default '{}',raw_app_meta_data jsonb default '{}');
      create table public.products(id uuid primary key,code text,product_type text,status text);
      create table public.platform_tenants(id uuid primary key,status text);
      create table public.product_tenants(product_id uuid,tenant_id uuid,status text);
      create table public.product_memberships(product_id uuid,tenant_id uuid,user_id uuid,status text,role_key text);
      create table coinops.operators(id uuid primary key,product_id uuid,tenant_id uuid,user_id uuid,status text);
      create table coinops.viewer_access(user_id uuid primary key,operator_id uuid,status text,display_name text,deleted_at timestamptz);
      create table coinops.trading_engines(id integer primary key);insert into coinops.trading_engines values(1),(2);
      insert into auth.users(id,raw_app_meta_data)values('${a}','{}'),('${b}','{"coinops_role":"VIEWER"}'),('${outsider}','{}');
      insert into public.products values('${sid}','coinops','internal','active');
      insert into public.platform_tenants values('${otherSid}','active');
      insert into public.product_tenants values('${sid}','${otherSid}','active');
      insert into public.product_memberships values('${sid}','${otherSid}','${a}','active','coinops.owner');
      insert into coinops.operators values('${sid}','${sid}','${otherSid}','${a}','ACTIVE');
      insert into coinops.viewer_access values('${b}','${sid}','ACTIVE','Viewer',null);`);
    await db.exec(readFileSync(new URL("../../../../supabase/migrations/20261011223915_coinops_commercial_billing.sql", import.meta.url), "utf8"));
    await act("service_role");
    assert.equal((await db.query<{ value: boolean }>("select coinops.billing_identity_active($1) as value", [a])).rows[0].value, true);
    assert.equal((await db.query<{ value: boolean }>("select coinops.billing_identity_active($1) as value", [outsider])).rows[0].value, false);
    const found = await db.query<{ value: { tenants: { id: string }[] } }>("select coinops.billing_discover_identities(null,'',100,null) as value");
    assert.deepEqual(new Set(found.rows[0].value.tenants.map(x => x.id)), new Set([a,b]));
    assert.equal((await apply(p())).rows[0].applied, true);
    await apply(p(b,otherSid));
    const nonce = randomUUID(), event = randomUUID();
    assert.equal((await apply(p(a,sid,2),nonce,event)).rows[0].applied,true);
    await assert.rejects(apply(p(a,sid,2),nonce,event),/duplicate key/);
    assert.equal((await apply(p(a,sid,2),randomUUID(),event)).rows[0].applied,false);
    assert.equal((await apply(p(a,sid,1))).rows[0].applied,false);
    await assert.rejects(apply(p(a,otherSid,3)),/billing_binding_conflict/);
    await assert.rejects(apply(p(a,randomUUID(),3)),/billing_binding_conflict/);
    await assert.rejects(apply(p(outsider,randomUUID())),/billing_identity_inactive/);
    await assert.rejects(apply(p(a,sid,3,{product_key:"onfood"})),/billing_invalid_projection/);
    const clean = (await db.query<{ projection: Record<string, unknown> }>("select projection from coinops.saas_billing_projections where user_id=$1",[a])).rows[0].projection;
    assert.equal(clean.checkout_url,undefined);assert.equal(clean.contact,undefined);assert.equal(clean.version,2);
    await act("authenticated",a);
    assert.deepEqual((await db.query<{ user_id: string }>("select user_id from coinops.saas_billing_projections")).rows.map(x=>x.user_id),[a]);
    await assert.rejects(apply(p(a,sid,3)),/permission denied/);
    await act("authenticated",b);
    assert.deepEqual((await db.query<{ user_id: string }>("select user_id from coinops.saas_billing_projections")).rows.map(x=>x.user_id),[b]);
    await act("anon");await assert.rejects(db.query("select * from coinops.saas_billing_projections"),/permission denied/);
    await db.exec("reset role;update coinops.viewer_access set status='INACTIVE';");
    await act("service_role");await apply(p(b,otherSid,2,{status:"canceled"}));
    await act("authenticated",b);assert.equal((await db.query("select * from coinops.saas_billing_projections")).rows.length,0);
    await act("service_role");
    const token=randomUUID();
    const claimed=await db.query<{ value:{claimed:boolean} }>("select coinops.claim_saas_billing_sync($1,$2) as value",[randomUUID(),token]);assert.equal(claimed.rows[0].value.claimed,true);
    assert.equal((await db.query<{ value:{claimed:boolean} }>("select coinops.claim_saas_billing_sync($1,$2) as value",[randomUUID(),randomUUID()])).rows[0].value.claimed,false);
    await assert.rejects(db.query("select coinops.finish_saas_billing_sync($1,null,null)",[randomUUID()]),/billing_lease_lost/);
    await db.query("select coinops.finish_saas_billing_sync($1,$2,null)",[token,sid]);
    await db.exec("reset role");assert.equal((await db.query<{ n:number }>("select count(*)::integer n from coinops.trading_engines")).rows[0].n,2);
  } finally {await db.close();}
});
