#!/usr/bin/env node
/** Deterministic source identity, not a workload/performance certificate.
 * --check is the build gate; --write regenerates the reviewed public constant
 * locally. No env, credentials, network, database or exchange access. */
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { existsSync, lstatSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, extname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const WORKLOAD_CONTRACT = "COINOPS_FINANCIAL_WORKLOAD_V1";
export const GENERATED_FILE = "apps/web/lib/supabase/workload-fingerprint.generated.ts";
const BUILDER = "tools/operations/financial-workload-fingerprint.mjs";
export const FINANCIAL_ENTRIES = Object.freeze([
  "apps/web/app/api/cron/live-execution/route.ts",
  "apps/web/app/api/cron/live-monitor/route.ts",
  "apps/web/app/api/cron/live-control/route.ts",
  "apps/web/app/api/cron/coinops-capacity/route.ts",
  "apps/web/app/api/cron/coinops-watchdog/route.ts",
  "apps/web/app/api/coinops-engine-control/route.ts",
  "apps/web/app/api/coinops-live-activation/route.ts",
  "apps/web/lib/execution/robot-v1-live-server.ts",
  "apps/web/lib/execution/engine-append-server.ts",
  "apps/web/lib/coinops-capacity/capacity-server.ts",
  "apps/web/next.config.mjs",
]);
const HASH = /^[a-f0-9]{64}$/;
const fail = code => { throw new Error(code); };
const normalize = value => value.replace(/\r\n/g, "\n");
const digest = value => createHash("sha256").update(value).digest("hex");
const allowed = path => !path.includes("..") && /^[a-zA-Z0-9_./-]+$/.test(path)
  && (path.startsWith("apps/web/") || path.startsWith("apps/live-executor/src/"))
  && !path.includes("/node_modules/") && !path.includes("/.env") && !path.endsWith(".test.ts")
  && !path.endsWith(".test.mjs");

/** TypeScript AST, including alias, re-export and dynamic literal imports.
 * An unresolved dynamic import/require is a release failure, not an omitted
 * dependency. Third-party executable versions are bound by package-lock. */
export function sourceImports(source, path, ts) {
  const kind = extname(path) === ".tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const file = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, kind);
  if (file.parseDiagnostics.length) fail("WORKLOAD_SOURCE_PARSE_FAILED");
  const imports = [];
  const literal = node => ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node);
  const visit = node => {
    if (ts.isIdentifier(node) && node.text === "require"
      && !(ts.isCallExpression(node.parent) && node.parent.expression === node))
      fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
      if (!literal(node.moduleSpecifier)) fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
      imports.push(node.moduleSpecifier.text);
    }
    if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference)) {
      if (!node.moduleReference.expression || !literal(node.moduleReference.expression)) fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
      imports.push(node.moduleReference.expression.text);
    }
    if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword
      || ts.isIdentifier(node.expression) && node.expression.text === "require")) {
      if (node.arguments.length !== 1 || !literal(node.arguments[0])) fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
      imports.push(node.arguments[0].text);
    }
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)
      && ["eval", "createRequire"].includes(node.expression.text)) fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
    ts.forEachChild(node, visit);
  };
  visit(file);
  if (imports.some(specifier => ["module", "node:module"].includes(specifier)))
    fail("WORKLOAD_DYNAMIC_IMPORT_UNREVIEWED");
  return [...new Set(imports)];
}
export function generatedManifest(fingerprint) {
  if (!HASH.test(fingerprint?.web_workload_sha256 ?? "") || !Number.isSafeInteger(fingerprint.file_count) || fingerprint.file_count < 1)
    fail("WORKLOAD_MANIFEST_INVALID");
  return `// Generated by tools/operations/financial-workload-fingerprint.mjs --write.\n`
    + `// Public source identity only; never an admission/performance certificate.\nimport "server-only";\n\n`
    + `export const WORKLOAD_CODE_CONTRACT = "${WORKLOAD_CONTRACT}" as const;\n`
    + `export const WORKLOAD_CODE_SHA256 = "${fingerprint.web_workload_sha256}";\n`
    + `export const WORKLOAD_CODE_FILE_COUNT = ${fingerprint.file_count};\n`;
}
export function computeFinancialWorkloadFingerprint({ repo = ROOT, entries = FINANCIAL_ENTRIES,
  readSource, fileExists, ts } = {}) {
  if (!ts) ts = createRequire(join(repo, "apps/web/package.json"))("typescript");
  const read = readSource ?? (path => {
    const file = resolve(repo, path);
    if (!allowed(path) && path !== BUILDER || !lstatSync(file).isFile()
      || realpathSync(file).toLowerCase() !== file.toLowerCase()) fail("WORKLOAD_SOURCE_IDENTITY_INVALID");
    return readFileSync(file, "utf8");
  });
  const exists = fileExists ?? (path => existsSync(resolve(repo, path)) && lstatSync(resolve(repo, path)).isFile());
  const config = ts.parseConfigFileTextToJson("apps/web/tsconfig.json", read("apps/web/tsconfig.json"));
  const compiler = config.config?.compilerOptions;
  if (config.error || config.config?.extends !== undefined || compiler?.baseUrl !== "." || compiler.moduleResolution !== "bundler"
    || JSON.stringify(compiler.paths) !== '{"@/*":["./*"]}'
    || ["rootDirs", "moduleSuffixes", "customConditions"].some(key => compiler[key] !== undefined))
    fail("WORKLOAD_ALIAS_CONFIGURATION_UNREVIEWED");
  const resolveImport = (from, specifier) => {
    if (specifier.startsWith("node:") || !specifier.startsWith(".") && !specifier.startsWith("@/")) return null;
    const base = specifier.startsWith("@/") ? `apps/web/${specifier.slice(2)}`
      : posix.normalize(posix.join(posix.dirname(from), specifier));
    if (!allowed(base)) fail("WORKLOAD_IMPORT_OUTSIDE_SOURCE");
    const candidates = [".ts", ".tsx", ".mjs", ".js", ".cjs", ".json"].includes(extname(base)) ? [base]
      : [base, ...[".ts", ".tsx", ".mjs", ".js", ".json"].map(ext => `${base}${ext}`),
      ...[".ts", ".tsx", ".mjs", ".js"].map(ext => `${base}/index${ext}`)];
    const resolved = candidates.find(path => path === GENERATED_FILE || exists(path));
    if (!resolved) fail("WORKLOAD_IMPORT_UNRESOLVED");
    return resolved;
  };
  const pending = [...entries], files = new Map();
  // Bind compiler/resolution behavior, not Next's generated include paths.
  // The actual file is still checked as tracked/unchanged by control-plane Git.
  const ordered = value => Array.isArray(value) ? value.map(ordered)
    : value && typeof value === "object" ? Object.fromEntries(Object.keys(value).sort().map(key => [key, ordered(value[key])])) : value;
  files.set("apps/web/tsconfig.json", digest(JSON.stringify(ordered(compiler))));
  while (pending.length) {
    const path = pending.pop();
    // Self-reference: the generated constant is validated byte-for-template
    // after computing the graph, never included in its own digest.
    if (path === GENERATED_FILE || files.has(path)) continue;
    if (!allowed(path)) fail("WORKLOAD_IMPORT_OUTSIDE_SOURCE");
    const source = normalize(read(path)); files.set(path, digest(source));
    if (path.endsWith(".json")) { JSON.parse(source); continue; }
    for (const specifier of sourceImports(source, path, ts)) {
      const dependency = resolveImport(path, specifier); if (dependency) pending.push(dependency);
    }
  }
  for (const path of ["apps/web/package.json", "apps/web/package-lock.json", BUILDER])
    files.set(path, digest(normalize(read(path))));
  const rows = [...files].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([path, sha256]) => ({ path, sha256 }));
  return { contract: WORKLOAD_CONTRACT, web_workload_sha256: digest(`${WORKLOAD_CONTRACT}\n`
    + rows.map(row => `${row.path}\0${row.sha256}\n`).join("")), file_count: rows.length, files: rows };
}
export function verifyFinancialWorkloadManifest({ repo = ROOT, ...options } = {}) {
  const result = computeFinancialWorkloadFingerprint({ repo, ...options });
  let actual;
  try { actual = normalize(readFileSync(resolve(repo, GENERATED_FILE), "utf8")); }
  catch { return fail("WORKLOAD_GENERATED_MANIFEST_MISSING"); }
  if (actual !== generatedManifest(result)) fail("WORKLOAD_GENERATED_MANIFEST_STALE");
  return { ...result, status: "WORKLOAD_CODE_FINGERPRINT_PASS" };
}
export function main(args = process.argv.slice(2)) {
  if (args.length > 1 || args.length === 1 && !["--check", "--write"].includes(args[0])) fail("WORKLOAD_USAGE_INVALID");
  if (args[0] === "--write") {
    const result = computeFinancialWorkloadFingerprint();
    writeFileSync(resolve(ROOT, GENERATED_FILE), generatedManifest(result), "utf8");
    return { status: "WORKLOAD_GENERATED_MANIFEST_UPDATED", web_workload_sha256: result.web_workload_sha256, file_count: result.file_count };
  }
  const result = verifyFinancialWorkloadManifest();
  return { status: result.status, web_workload_sha256: result.web_workload_sha256, file_count: result.file_count };
}
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  try { process.stdout.write(`${JSON.stringify(main(), null, 2)}\n`); }
  catch (error) { process.stderr.write(`${JSON.stringify({ status: "FAIL", code: /^WORKLOAD_[A-Z0-9_]+$/.test(error?.message ?? "")
    ? error.message : "WORKLOAD_FINGERPRINT_FAILED" })}\n`); process.exitCode = 1; }
}
